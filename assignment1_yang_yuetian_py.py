def draw_square():
    print("\n--- Drawing Square ---")
    while True:
        try:
            side = float(
                input(
                    "Enter side length for square (e.g., 100 or 150): "
                )
            )
            if side <= 0:
                print("Side length must be greater than 0.")
                continue
            break
        except ValueError:
            print("Invalid input! Please enter a valid number.")

    color = get_color("Square")

    setup_canvas()
    t.color(color)

    # Draw square using a for-loop
    for _ in range(4):
        t.forward(int(side))
        t.left(90)


