# 2. Draw Triangle (Coordinate-based for precise closing)
# ==========================================
def draw_triangle():
    print("\n--- Drawing Triangle ---")
    while True:
        try:
            a = float(input("Enter length for side a (e.g., 100): "))
            b = float(input("Enter length for side b (e.g., 100): "))
            c = float(input("Enter length for side c (e.g., 100): "))

            if a <= 0 or b <= 0 or c <= 0:
                print("All side lengths must be greater than 0!")
                continue

            # Verify triangle inequality theorem
            valid_sum = (a + b > c) and (a + c > b) and (b + c > a)
            valid_diff = (
                (abs(a - b) < c) and (abs(a - c) < b) and (abs(b - c) < a)
            )

            if valid_sum and valid_diff:
                break
            else:
                print(
                    "Invalid triangle dimensions! "
                    "Sum of any two sides must be greater than the third side, "
                    "and difference must be less than the third side."
                )
        except ValueError:
            print("Invalid input! Please enter valid numbers.")

    color = get_color("Triangle")

    # Calculate internal angle C (between side a and side b) using Law of Cosines
    cos_C = (a**2 + b**2 - c**2) / (2 * a * b)
    angle_C = math.acos(cos_C)

    setup_canvas()
    t.color(color)

    # ColabTurtle canvas default size is 800x500, set starting point
    start_x, start_y = 350, 300

    # Calculate exact 3 vertices coordinates
    # Vertex 1: Start point
    # Vertex 2: Move right along base line (side a)
    v1 = (start_x, start_y)
    v2 = (start_x + a, start_y)

    # Vertex 3: Calculated using angle C and side b
    v3 = (
        start_x + b * math.cos(angle_C),
        start_y - b * math.sin(angle_C),  # ColabTurtle Y axis points downward
    )

    # Draw closed triangle path connecting the 3 coordinates
    t.penup()
    t.goto(int(v1[0]), int(v1[1]))
    t.pendown()

    t.goto(int(v2[0]), int(v2[1]))
    t.goto(int(v3[0]), int(v3[1]))
    t.goto(int(v1[0]), int(v1[1]))  # Guaranteed exact closure2

