import math
import ColabTurtle.Turtle as t


def setup_canvas():
    """Initialize canvas, set white background, and reset turtle settings."""
    t.initializeTurtle()
    t.bgcolor("white")  # Set background to white so lines are clearly visible
    t.speed(5)
    t.pensize(3)


def get_color(shape_name):
    """Validate and restrict color choices to strictly Red, Yellow, or Blue."""
    color_map = {"1": "red", "2": "yellow", "3": "blue"}
    while True:
        choice = (
            input(
                f"Select color for {shape_name} (1: Red / 2: Yellow / 3: Blue): "
            )
            .strip()
            .lower()
        )
        if choice in color_map:
            return color_map[choice]
        elif choice in ["red", "yellow", "blue"]:
            return choice
        else:
            print(
                "Invalid input! Color must strictly be Red (1), Yellow (2), or Blue (3)."
            )


