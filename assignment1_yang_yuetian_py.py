def draw_star():
    print("\n--- Drawing Regular 5-Point Star ---")
    while True:
        try:
            side = float(
                input(
                    "Enter side length for star (e.g., 100 or 150): "
                )
            )
            if side <= 0:
                print("Side length must be greater than 0.")
                continue
            break
        except ValueError:
            print("Invalid input! Please enter a valid number.")

    color = get_color("Star")

    setup_canvas()
    t.color(color)

    # Regular 5-pointed star requires turning 144 degrees at each point
    for _ in range(5):
        t.forward(int(side))
        t.right(144)


